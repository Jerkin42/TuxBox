"""Write src/bc1_tables.rs from bcpack-rs's fitted BC1 tables.

Usage: python gen_bc1_tables.py bc1_window.json bc1_quad_table.json > src/bc1_tables.rs

The inputs are data/bc1_window.json and data/bc1_quad_table.json of
https://github.com/Ahmet-Dedeler/bcpack-rs at REVISION. Both were fitted on
retail texture data before any other BCPack decoder was published. Later
revisions replaced 75 window slots with values taken from another decoder;
those are deliberately not used.
"""
import hashlib
import json
import sys

REVISION = "5bf5cc56ed56f1ababf1f9592300bd182ff90bd8"
WIDTHS = (5, 6, 5, 5, 6, 5)


def main(window_path, quad_path):
    window_text = open(window_path, "rb").read()
    quad_text = open(quad_path, "rb").read()
    slots = json.loads(window_text)["slots"]
    assert len(slots) == 256
    entries = json.loads(quad_text)["entries"]
    codes = [None] * 256
    for entry in entries:
        assert codes[entry["sym"]] is None and len(entry["codes"]) == 4
        codes[entry["sym"]] = entry["codes"]
    assert all(c is not None and all(0 <= v <= 3 for v in c) for c in codes)
    print(f"""// bcpack-rs by Ahmet Dedeler (https://github.com/Ahmet-Dedeler, https://ahmetdedeler.com)
// Source: https://github.com/Ahmet-Dedeler/bcpack-rs
// SPDX-License-Identifier: MIT OR Apache-2.0
// If you copy, vendor or port this file, keep this header and credit bcpack-rs in your README.
//
// Generated by gen_bc1_tables.py from bcpack-rs {REVISION}:
// data/bc1_window.json (SHA-256 {hashlib.sha256(window_text).hexdigest()})
// data/bc1_quad_table.json (SHA-256 {hashlib.sha256(quad_text).hexdigest()})
// Values only. Do not edit by hand.
//! BC1 constants fitted on retail texture data by bcpack-rs. They are not the
//! hardware's own tables, so a decoded block can differ from the console's.

/// Endpoint fields R0 G0 B0 R1 G1 B1 that a reference before the first block
/// reads, by slot; `None` where no fit exists (decoded as zeros).
#[rustfmt::skip]
pub const WINDOW: [Option<[u8; 6]>; 256] = [""")
    for s, slot in enumerate(slots):
        if slot is None:
            print(f"    None, // {s}")
        else:
            value = slot["value"]
            assert len(value) == 6 and all(0 <= v < 1 << w for v, w in zip(value, WIDTHS))
            print(f"    Some([{', '.join(map(str, value))}]), // {s}")
    print("""];

/// The BC1 codes of a 2x2 pixel group for each index-lane symbol, in the
/// group's order top-left, top-right, bottom-left, bottom-right.
#[rustfmt::skip]
pub const QUADS: [[u8; 4]; 256] = [""")
    for s in range(0, 256, 8):
        print("    " + " ".join(f"[{', '.join(map(str, codes[k]))}]," for k in range(s, s + 8)))
    print("];")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
